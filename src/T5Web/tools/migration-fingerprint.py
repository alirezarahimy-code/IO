#!/usr/bin/env python3
"""Migration fingerprint: prove a moved database is the database you moved.

Why this exists
---------------
Neither rewrite owns the schema. Both portals attach to the T5 databases that the
vendor's installer created (``ReportT5V3`` and ``Personnel``), so "migrating" is
never a schema change - it is a move. A move can still go wrong in ways nobody
notices until a report is wrong:

  * a table restored from an older backup (row counts differ),
  * an IDENTITY seed that came back as 1 (the next INSERT silently reuses a key),
  * a different collation on the target server (Persian text sorts differently,
    ``N'ي'`` and ``N'ی'`` stop matching),
  * one catalog restored from a different point in time than the other.

This tool does two things, both offline:

  --sql       print a read-only T-SQL script that writes one line per table
              ("catalog|table|rows"), one line per identity table, and a few
              meta lines. Run it on the source before the move and on the target
              after, then compare the two text files.

  --compare   diff two fingerprints and exit non-zero on a real difference.

The table list is generated from engine/relations.json (the model built from the
vendor DDL and engine ORM), so the fingerprint can never cover a table that does
not exist, and it cannot quietly lose a table that was added later.

    python3 tools/migration-fingerprint.py --sql > source.txt
    python3 tools/migration-fingerprint.py --compare source.txt target.txt

Contract with the schema model: every ``t5`` and ``personnel`` table appears once.
The three portal-owned tables are excluded by default - a new portal install is
supposed to have them empty, so comparing them means nothing. ``--include-portal``
adds them for an in-place move.
"""
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
MODEL = os.path.join(ROOT, "engine", "relations.json")

DEFAULT_CATALOGS = {"t5": "ReportT5V3", "personnel": "Personnel"}
PORTAL_CATALOG = "portal"
PORTAL_DB = "ReportT5V3"


def load_model():
    with open(MODEL, encoding="utf-8") as handle:
        model = json.load(handle)
    catalogs = model.get("databases") or {}
    if not catalogs:
        raise SystemExit("engine/relations.json has no table->catalog map.")
    return model, catalogs


def tables_for(catalogs, include_portal=False):
    """[(catalog, table)] sorted, portal optional."""
    allowed = set(DEFAULT_CATALOGS)
    if include_portal:
        allowed.add(PORTAL_CATALOG)
    picked = []
    for name, entry in catalogs.items():
        database = entry.get("database") if isinstance(entry, dict) else entry
        if database in allowed:
            picked.append((database, name))
    return sorted(set(picked), key=lambda pair: (pair[0], pair[1].lower()))


def database_for(catalog):
    return PORTAL_DB if catalog == PORTAL_CATALOG else DEFAULT_CATALOGS[catalog]


def build_sql(include_portal=False, t5_db=None, personnel_db=None):
    model, catalogs = load_model()
    t5_db = t5_db or DEFAULT_CATALOGS["t5"]
    personnel_db = personnel_db or DEFAULT_CATALOGS["personnel"]
    names = {"t5": t5_db, "personnel": personnel_db, "portal": PORTAL_DB}
    picked = tables_for(catalogs, include_portal)

    out = []
    out.append("/* =====================================================================")
    out.append("   T5Web migration fingerprint - READ ONLY")
    out.append("   ---------------------------------------------------------------------")
    out.append("   Generated by tools/migration-fingerprint.py from engine/relations.json.")
    out.append("   Do not hand-edit: regenerate, then compare the two runs.")
    out.append("")
    out.append("   Run on the SOURCE before the move and on the TARGET after it, save each")
    out.append("   result as text, and diff them with:")
    out.append("")
    out.append("       python3 tools/migration-fingerprint.py --compare source.txt target.txt")
    out.append("")
    out.append("   This script writes nothing. It only counts rows and reads identity seeds.")
    out.append("   ===================================================================== */")
    out.append("")
    out.append("SET NOCOUNT ON;")
    out.append("")
    out.append("DECLARE @out TABLE (line nvarchar(400) NOT NULL);")
    out.append("")
    out.append("/* ---------- meta: what the two runs must agree on ---------- */")
    # Every value is wrapped in ISNULL: a single NULL anywhere in a concatenation makes
    # the whole line NULL, and the column does not accept NULL - on LocalDB the first
    # meta line killed the script with "Cannot insert the value NULL into column 'line'".
    out.append("INSERT @out (line) SELECT N'meta|sqlversion|' + "
               "ISNULL(CONVERT(nvarchar(128), SERVERPROPERTY('ProductVersion')), N'?') + N'|' + "
               "ISNULL(CONVERT(nvarchar(128), SERVERPROPERTY('Edition')), N'?');")
    for catalog, db in (("t5", t5_db), ("personnel", personnel_db)):
        out.append(
            "INSERT @out (line) SELECT N'meta|collation|{db}|' + "
            "ISNULL(CONVERT(nvarchar(128), DATABASEPROPERTYEX(N'{db}', 'Collation')), N'?');".format(db=db))
        out.append(
            "INSERT @out (line) SELECT N'meta|compat|{db}|' + "
            "ISNULL(CONVERT(nvarchar(10), (SELECT compatibility_level FROM sys.databases "
            "WHERE name = N'{db}')), N'?');".format(db=db))
    out.append("")
    out.append("/* ---------- row counts: one line per table ---------- */")
    # A customer database installed from an older engine build may legitimately be
    # missing a table the current model knows about. Report it as MISSING instead of
    # stopping the script with "Invalid object name" - then source and target are
    # compared on the same footing.
    for catalog, table in picked:
        db = names[catalog]
        object_name = "[{db}].[dbo].[{table}]".format(db=db, table=table)
        out.append(
            "IF OBJECT_ID(N'{object_name}') IS NULL\n"
            "    INSERT @out (line) VALUES (N'table|{catalog}|{table}|MISSING');\n"
            "ELSE\n"
            "    INSERT @out (line) SELECT N'table|{catalog}|{table}|' + "
            "CONVERT(nvarchar(30), COUNT_BIG(*)) FROM {object_name};".format(
                object_name=object_name, catalog=catalog, table=table))
    out.append("")
    out.append("/* ---------- identity seeds: a restored seed of 1 reuses keys ---------- */")
    for catalog, db in (("t5", t5_db), ("personnel", personnel_db)):
        out.append(
            "INSERT @out (line)\n"
            "SELECT N'identity|{catalog}|' + t.name + N'|' + ISNULL(CONVERT(nvarchar(30), IDENT_CURRENT(N'{db}.dbo.' + t.name)), N'0')\n"
            "FROM [{db}].sys.tables t\n"
            "WHERE EXISTS (SELECT 1 FROM [{db}].sys.identity_columns ic WHERE ic.object_id = t.object_id)\n"
            "  AND t.is_ms_shipped = 0;".format(catalog=catalog, db=db))
    out.append("")
    out.append("/* ---------- the answer ---------- */")
    out.append("SELECT line FROM @out ORDER BY line;")
    out.append("")
    text = "\n".join(line for line in out if line.strip() != "")
    return text + "\n"


def parse(text):
    """Fingerprint text -> {'meta': {k: v}, 'table': {}, 'identity': {}}."""
    meta, rows, seeds = {}, {}, {}
    for raw in text.replace("\ufeff", "").splitlines():
        line = raw.strip()
        if not line or line.startswith("/*") or line.startswith("--") or line.startswith("*"):
            continue
        parts = line.split("|")
        kind = parts[0]
        if kind == "meta" and len(parts) >= 4:
            meta[parts[2] + "." + parts[1]] = "|".join(parts[3:])
        elif kind == "table" and len(parts) >= 4:
            # "MISSING" is a legitimate value: an older install may not have the table.
            rows[(parts[1], parts[2])] = parts[3].strip()
        elif kind == "identity" and len(parts) >= 4:
            seeds[(parts[1], parts[2])] = int(parts[3])
    return {"meta": meta, "table": rows, "identity": seeds}


def compare(source_text, target_text, strict_identity=False, strict_meta=False):
    """Returns (errors, warnings) as lists of Persian-ready English lines."""
    src = parse(source_text)
    tgt = parse(target_text)
    errors, warnings = [], []
    if not src["table"]:
        errors.append("source fingerprint has no table lines - wrong file?")
    if not tgt["table"]:
        errors.append("target fingerprint has no table lines - wrong file?")

    for key in sorted(set(src["table"]) - set(tgt["table"])):
        errors.append("missing on target: %s.%s (%s rows on source)"
                      % (key[0], key[1], src["table"][key]))
    for key in sorted(set(tgt["table"]) - set(src["table"])):
        errors.append("unexpected on target: %s.%s (%s rows)" % (key[0], key[1], tgt["table"][key]))
    for key in sorted(set(src["table"]) & set(tgt["table"])):
        if src["table"][key] != tgt["table"][key]:
            errors.append("row count differs: %s.%s source=%s target=%s"
                          % (key[0], key[1], src["table"][key], tgt["table"][key]))

    for key in sorted(set(src["identity"]) & set(tgt["identity"])):
        before, after = src["identity"][key], tgt["identity"][key]
        if before != after:
            line = "identity seed differs: %s.%s source=%d target=%d" % (key[0], key[1], before, after)
            (errors if strict_identity else warnings).append(line)
    for key in sorted(set(src["identity"]) - set(tgt["identity"])):
        warnings.append("no identity seed reported on target for %s.%s" % (key[0], key[1]))

    for key in sorted(set(src["meta"]) & set(tgt["meta"])):
        if src["meta"][key] != tgt["meta"][key]:
            line = "%s differs: source=%s target=%s" % (key, src["meta"][key], tgt["meta"][key])
            (errors if strict_meta else warnings).append(line)
    return errors, warnings


def self_test():
    """No SQL Server here, so the comparison logic is tested against fixtures."""
    model, catalogs = load_model()
    picked = tables_for(catalogs, include_portal=False)
    lines = ["meta|collation|ReportT5V3|Persian_100_CI_AS",
             "meta|collation|Personnel|Persian_100_CI_AS"]
    for index, (catalog, table) in enumerate(picked):
        lines.append("table|%s|%s|%d" % (catalog, table, index + 1))
        lines.append("identity|%s|%s|%d" % (catalog, table, index + 100))
    base = "\n".join(lines) + "\n"

    problems = []
    errors, warnings = compare(base, base)
    if errors or warnings:
        problems.append("identical fingerprints reported %d error(s), %d warning(s)"
                        % (len(errors), len(warnings)))

    first_catalog, first_table = picked[0]
    moved = base.replace("table|%s|%s|1" % (first_catalog, first_table),
                         "table|%s|%s|9" % (first_catalog, first_table), 1)
    errors, _ = compare(base, moved)
    if len(errors) != 1:
        problems.append("a changed row count produced %d error(s), expected 1" % len(errors))

    dropped = "\n".join(
        line for line in lines
        if line != "table|%s|%s|1" % (first_catalog, first_table)
        and line != "identity|%s|%s|100" % (first_catalog, first_table)) + "\n"
    errors, _ = compare(base, dropped)
    if not errors:
        problems.append("a missing table was not detected")

    seeded = base.replace("identity|%s|%s|100" % (first_catalog, first_table),
                          "identity|%s|%s|1" % (first_catalog, first_table), 1)
    errors, warnings = compare(base, seeded)
    if errors or not warnings:
        problems.append("a reset identity seed must be a warning by default")
    errors, _ = compare(base, seeded, strict_identity=True)
    if not errors:
        problems.append("--strict-identity did not turn the seed drift into an error")

    sql = build_sql()
    regenerated = build_sql()
    if sql != regenerated:
        problems.append("the generated SQL is not deterministic")
    for catalog, table in picked:
        if "N'table|%s|%s|'" % (catalog, table) not in sql:
            problems.append("the SQL does not count %s.%s" % (catalog, table))
        if "OBJECT_ID(N'[%s].[dbo].[%s]')" % (database_for(catalog), table) not in sql:
            problems.append("the SQL counts %s.%s without an existence guard" % (catalog, table))
    if "|MISSING" not in sql:
        problems.append("the SQL has no MISSING branch for an older install")
    if "N'table|portal|" in sql:
        problems.append("portal-owned tables must be excluded unless --include-portal")
    counted = sql.count("INSERT @out (line) SELECT N'table|")
    if counted != len(picked):
        problems.append("the SQL counts %d tables, the model has %d" % (counted, len(picked)))
    if "T5WebAudit" in sql:
        problems.append("the SQL reaches into a portal table it should not touch")

    if problems:
        print("FAIL: migration fingerprint self-test")
        for problem in problems:
            print("  - " + problem)
        return 1
    print("OK: migration fingerprint (%d tables, %d catalogs, comparison logic tested)"
          % (len(picked), len({c for c, _ in picked})))
    return 0


def main(argv):
    args = list(argv)
    if "--sql" in args:
        include_portal = "--include-portal" in args
        t5_db = personnel_db = None
        for index, arg in enumerate(args):
            if arg == "--t5-db" and index + 1 < len(args):
                t5_db = args[index + 1]
            if arg == "--personnel-db" and index + 1 < len(args):
                personnel_db = args[index + 1]
        sys.stdout.write(build_sql(include_portal, t5_db, personnel_db))
        return 0

    if "--compare" in args:
        at = args.index("--compare")
        rest = [a for a in args[at + 1:] if not a.startswith("--")]
        if len(rest) != 2:
            print("usage: --compare SOURCE.txt TARGET.txt [--strict-identity] [--strict-meta]")
            return 2
        # utf-8-sig: PowerShell's Out-File writes a BOM, and a BOM in front of the
        # first line was enough to make every table line unreadable once.
        with open(rest[0], encoding="utf-8-sig") as handle:
            source_text = handle.read()
        with open(rest[1], encoding="utf-8-sig") as handle:
            target_text = handle.read()
        errors, warnings = compare(source_text, target_text,
                                   "--strict-identity" in args, "--strict-meta" in args)
        for warning in warnings:
            print("WARN  " + warning)
        for error in errors:
            print("DIFF  " + error)
        if errors:
            print("FAIL: %d difference(s); the move is not verified." % len(errors))
            return 1
        print("OK: fingerprints match (%d tables%s)"
              % (len(parse(source_text)["table"]),
                 ", %d warning(s)" % len(warnings) if warnings else ""))
        return 0

    # Default and --check: the gate the build runs.
    return self_test()


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
