using System;
using System.Collections.Generic;
using System.Globalization;
using System.Linq;
using T5Web.Domain.Interfaces;
using T5Web.Domain.Models;

namespace T5Web.Application.Modules
{
    /// <summary>
    /// Validation and coercion for every module screen.
    ///
    /// The web layer hands over the raw form dictionary; this class decides what is
    /// valid and produces the typed row. Keeping it here (and not in the controller)
    /// means the rules are the same for the browser, for the tests and for any future
    /// import path - and it keeps Application free of System.Web.
    /// </summary>
    public sealed class ModuleService
    {
        private readonly IModuleStore _store;

        public ModuleService(IModuleStore store)
        {
            if (store == null)
            {
                throw new ArgumentNullException(nameof(store));
            }
            _store = store;
        }

        public ModulePage Page(ModuleDescriptor descriptor, string term, int page, int pageSize = 50)
        {
            if (descriptor == null)
            {
                throw new ArgumentNullException(nameof(descriptor));
            }
            if (page < 1)
            {
                page = 1;
            }
            if (pageSize < 10 || pageSize > 200)
            {
                pageSize = 50;
            }
            return _store.Query(descriptor, term ?? string.Empty, page, pageSize);
        }

        public ModuleRow Get(ModuleDescriptor descriptor, IDictionary<string, string> key)
        {
            IReadOnlyDictionary<string, string> frozen;
            if (!TryFreeze(descriptor, key, false, out frozen))
            {
                return null;
            }
            return _store.Get(descriptor, frozen);
        }

        public IReadOnlyList<KeyValuePair<string, string>> Options(ModuleDescriptor descriptor)
        {
            return _store.Options(descriptor);
        }

        /// <summary>
        /// Turns the posted strings into a row, or returns the first readable problem.
        ///
        /// Every rule is attached to the field, not repeated per module: required,
        /// length, numeric range, date/time parse, and select membership. A value that
        /// cannot be typed is rejected rather than coerced, because "0" written into a
        /// date column is worse than a validation message.
        /// </summary>
        public OperationResult Build(ModuleDescriptor descriptor, IDictionary<string, string> form,
                                     bool isNew, out ModuleRow row)
        {
            row = new ModuleRow();
            if (descriptor == null)
            {
                return OperationResult.Fail("ماژول مشخص نیست.");
            }
            if (form == null)
            {
                form = new Dictionary<string, string>();
            }

            foreach (ModuleField field in descriptor.Fields)
            {
                string raw = Value(form, field.Column);
                bool missing = string.IsNullOrWhiteSpace(raw);

                if (missing)
                {
                    if (field.IsKey && field.Identity)
                    {
                        continue; // generated by the database
                    }
                    if (field.Required && (isNew || field.IsKey))
                    {
                        return OperationResult.Fail("مقدار «" + field.LabelFa + "» الزامی است.");
                    }
                    row[field.Column] = field.Kind == FieldKind.Boolean ? (object)false : null;
                    continue;
                }

                switch (field.Kind)
                {
                    case FieldKind.Text:
                    case FieldKind.Select:
                    {
                        string text = raw.Trim();
                        if (field.MaxLength > 0 && text.Length > field.MaxLength)
                        {
                            return OperationResult.Fail("«" + field.LabelFa + "» بیش از " + field.MaxLength + " نویسه است.");
                        }
                        if (field.Kind == FieldKind.Select && field.Options != null && field.Options.Count > 0)
                        {
                            int selected;
                            if (!int.TryParse(text, NumberStyles.Integer, CultureInfo.InvariantCulture, out selected) ||
                                field.Options.All(o => o.Key != selected))
                            {
                                return OperationResult.Fail("مقدار انتخاب‌شده برای «" + field.LabelFa + "» معتبر نیست.");
                            }
                        }
                        row[field.Column] = text;
                        break;
                    }

                    case FieldKind.Number:
                    {
                        long integer;
                        if (long.TryParse(raw.Trim(), NumberStyles.Integer, CultureInfo.InvariantCulture, out integer))
                        {
                            if (field.Min.HasValue && integer < field.Min.Value)
                            {
                                return OperationResult.Fail("«" + field.LabelFa + "» کمتر از حد مجاز است.");
                            }
                            if (field.Max.HasValue && integer > field.Max.Value)
                            {
                                return OperationResult.Fail("«" + field.LabelFa + "» بیشتر از حد مجاز است.");
                            }
                            row[field.Column] = integer;
                            break;
                        }
                        double real;
                        if (double.TryParse(raw.Trim(), NumberStyles.Float, CultureInfo.InvariantCulture, out real))
                        {
                            if (field.Min.HasValue && real < field.Min.Value)
                            {
                                return OperationResult.Fail("«" + field.LabelFa + "» کمتر از حد مجاز است.");
                            }
                            if (field.Max.HasValue && real > field.Max.Value)
                            {
                                return OperationResult.Fail("«" + field.LabelFa + "» بیشتر از حد مجاز است.");
                            }
                            row[field.Column] = real;
                            break;
                        }
                        // Persian digits are common in copy-pasted input; accept them once.
                        long persian;
                        if (TryPersianInteger(raw, out persian))
                        {
                            row[field.Column] = persian;
                            break;
                        }
                        return OperationResult.Fail("«" + field.LabelFa + "» باید عدد باشد.");
                    }

                    case FieldKind.Boolean:
                        row[field.Column] = ModuleRow.IsTrue(raw) || raw.Trim() == "true";
                        break;

                    case FieldKind.Date:
                    {
                        // Exact ISO only. A Jalali date ("1404/08/03") parses happily as a
                        // Gregorian one and would silently land 622 years away.
                        DateTime date;
                        if (!DateTime.TryParseExact(raw.Trim(), "yyyy-MM-dd", CultureInfo.InvariantCulture,
                                                    DateTimeStyles.None, out date))
                        {
                            return OperationResult.Fail("«" + field.LabelFa + "» تاریخ معتبری نیست (قالب: yyyy-MM-dd).");
                        }
                        if (date.Year < 1900 || date.Year > 2200)
                        {
                            return OperationResult.Fail("«" + field.LabelFa + "» خارج از بازه مجاز است.");
                        }
                        row[field.Column] = date;
                        break;
                    }

                    case FieldKind.Time:
                    {
                        TimeSpan time;
                        if (!TimeSpan.TryParse(raw.Trim(), CultureInfo.InvariantCulture, out time) ||
                            time < TimeSpan.Zero || time >= TimeSpan.FromDays(1))
                        {
                            return OperationResult.Fail("«" + field.LabelFa + "» ساعت معتبری نیست (قالب: HH:mm).");
                        }
                        row[field.Column] = time;
                        break;
                    }

                    default:
                        row[field.Column] = raw.Trim();
                        break;
                }
            }

            return OperationResult.Ok();
        }

        public OperationResult Save(ModuleDescriptor descriptor, ModuleRow row, bool isNew)
        {
            if (descriptor.ReadOnly)
            {
                return OperationResult.Fail("این صفحه فقط خواندنی است.");
            }
            if (isNew && !descriptor.AllowCreate)
            {
                return OperationResult.Fail("افزودن سطر جدید در این ماژول مجاز نیست.");
            }
            return _store.Save(descriptor, row, isNew);
        }

        public OperationResult Delete(ModuleDescriptor descriptor, IDictionary<string, string> key)
        {
            if (!descriptor.AllowDelete)
            {
                return OperationResult.Fail("حذف در این ماژول مجاز نیست.");
            }
            IReadOnlyDictionary<string, string> frozen;
            if (!TryFreeze(descriptor, key, true, out frozen))
            {
                // A partial key must never be treated as a wildcard: that is how a
                // "delete one row" becomes "delete every row with this badge number".
                return OperationResult.Fail("کلید سطر کامل نیست؛ برای حذف باید همه بخش‌های کلید مشخص باشد.");
            }
            return _store.Delete(descriptor, frozen);
        }

        /// <summary>Key dictionary, validated to contain every key column exactly once.</summary>
        private static bool TryFreeze(ModuleDescriptor descriptor, IDictionary<string, string> key,
                                      bool required, out IReadOnlyDictionary<string, string> frozen)
        {
            var values = new Dictionary<string, string>(StringComparer.OrdinalIgnoreCase);
            foreach (ModuleField field in descriptor.Keys)
            {
                string value = key != null && key.ContainsKey(field.Column) ? key[field.Column] : null;
                if (string.IsNullOrWhiteSpace(value))
                {
                    if (required)
                    {
                        frozen = null;
                        return false;
                    }
                    continue;
                }
                values[field.Column] = value.Trim();
            }
            frozen = values;
            return true;
        }

        private static string Value(IDictionary<string, string> form, string column)
        {
            foreach (var pair in form)
            {
                if (string.Equals(pair.Key, column, StringComparison.OrdinalIgnoreCase))
                {
                    return pair.Value;
                }
            }
            return null;
        }

        private static bool TryPersianInteger(string raw, out long value)
        {
            value = 0;
            if (string.IsNullOrWhiteSpace(raw))
            {
                return false;
            }
            var builder = new System.Text.StringBuilder();
            foreach (char c in raw.Trim())
            {
                if (c >= '\u06F0' && c <= '\u06F9')
                {
                    builder.Append((char)('0' + (c - '\u06F0')));
                }
                else if (c >= '\u0660' && c <= '\u0669')
                {
                    builder.Append((char)('0' + (c - '\u0660')));
                }
                else
                {
                    builder.Append(c);
                }
            }
            return long.TryParse(builder.ToString(), NumberStyles.Integer, CultureInfo.InvariantCulture, out value);
        }
    }
}
