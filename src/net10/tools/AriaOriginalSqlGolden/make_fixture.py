#!/usr/bin/env python3
"""Create an isolated synthetic dbo.UserInfo fixture from TWF 4.28's pinned EDMX.

The only permitted database name starts AriaGoldenDb_ and is generated by the
CI runner. Never read original Web.config, MDF, production rows or passwords.
No SQL is run by this script; the SQL file is written only to runner temp.
"""
import hashlib
import pathlib
import re
import sys
import xml.etree.ElementTree as ET

PIN = "468e43ea66b9c591384ddcd033918e6f563a85b4caa2b6e6c4e8b85a4484050f"


def local(tag):
    return tag.rsplit("}", 1)[-1]


def store_schema(binary):
    start = 0
    while (pos := binary.find(b'<Schema Namespace="personnelModel.Store"', start)) >= 0:
        start = pos + 8
        end = binary.find(b"</Schema>", pos)
        if end < 0 or end - pos > 120000:
            continue
        root = ET.fromstring(binary[pos:end + 9])
        if root.attrib.get("Provider") == "System.Data.SqlClient":
            return root
    raise ValueError("pinned original Personnel SQL model unavailable")


def make_sql(binary, database):
    if not re.fullmatch(r"AriaGoldenDb_[0-9]{6,20}", database):
        raise ValueError("not a CI-owned synthetic database name")
    schema = store_schema(binary)
    tables = [e for e in schema.iter() if local(e.tag) == "EntitySet" and
              e.attrib.get("Name") == "UserInfo" and e.attrib.get("Schema") == "dbo"]
    entities = [e for e in schema.iter() if local(e.tag) == "EntityType" and
                e.attrib.get("Name") == "UserInfo"]
    if len(tables) != 1 or len(entities) != 1:
        raise ValueError("unexpected original store table mapping")
    entity = entities[0]
    keys = [e.attrib.get("Name") for k in entity if local(k.tag) == "Key"
            for e in k if local(e.tag) == "PropertyRef"]
    if keys != ["BadgeNumber"]:
        raise ValueError("unexpected original user table key")
    columns = []
    names = set()
    for prop in entity:
        if local(prop.tag) != "Property":
            continue
        name = prop.attrib["Name"]
        if not re.fullmatch(r"[A-Za-z][A-Za-z0-9]*", name) or name in names:
            raise ValueError("unexpected original SQL column identifier")
        names.add(name)
        kind = prop.attrib["Type"].lower()
        if kind in ("bigint", "int", "bit", "datetime", "image"):
            sqltype = kind.upper()
        elif kind == "nvarchar" and prop.attrib.get("MaxLength", "").isdigit():
            maximum = int(prop.attrib["MaxLength"])
            if not 1 <= maximum <= 250:
                raise ValueError("unexpected original NVARCHAR length")
            sqltype = "NVARCHAR({})".format(maximum)
        else:
            raise ValueError("unhandled original SQL type (fail closed): " + kind)
        null = prop.attrib.get("Nullable") != "false"
        suffix = "NULL" if null else "NOT NULL"
        if not null and name not in ("BadgeNumber", "UserName", "Password"):
            if kind in ("int", "bigint", "bit"):
                suffix += " DEFAULT (0)"
            elif kind == "datetime":
                suffix += " DEFAULT (CONVERT(DATETIME, '20000101', 112))"
            elif kind == "nvarchar":
                suffix += " DEFAULT (N'fixture')"
            else:
                raise ValueError("required unsupported fixture field: " + name)
        columns.append("    [{}] {} {}".format(name, sqltype, suffix))
    expected = {"BadgeNumber", "UserName", "Password", "ValidFrom", "ValidTo",
                "WebUser", "FiredDate"}
    if not expected.issubset(names) or len(columns) < 25:
        raise ValueError("original Personnel user fixture is incomplete")
    # Every literal below is synthetic; no production value or original config.
    return """SET NOCOUNT ON;
IF DB_ID(N'{db}') IS NOT NULL THROW 51011, 'Golden database name collision', 1;
GO
CREATE DATABASE [{db}];
GO
USE [{db}];
GO
CREATE TABLE [dbo].[UserInfo] (
{columns},
    CONSTRAINT [PK_AriaGolden_UserInfo] PRIMARY KEY ([BadgeNumber])
);
GO
INSERT INTO [dbo].[UserInfo] ([BadgeNumber], [UserName], [Password], [WebUser],
                                [ValidFrom], [ValidTo], [FiredDate])
VALUES
(900101, N'fixture-aria-active', N'fixture-aria-password', 1,
 CONVERT(DATETIME, '20000101', 112), CONVERT(DATETIME, '20500101', 112), NULL),
(900102, N'fixture-aria-future', N'fixture-aria-future-pass', 1,
 DATEADD(DAY, 2, GETDATE()), CONVERT(DATETIME, '20500101', 112), NULL),
(900103, N'fixture-aria-expired', N'fixture-aria-expired-pass', 1,
 CONVERT(DATETIME, '20000101', 112), DATEADD(DAY, -2, GETDATE()), NULL),
(900104, N'fixture-aria-disabled', N'fixture-aria-disabled-pass', 0,
 CONVERT(DATETIME, '20000101', 112), CONVERT(DATETIME, '20500101', 112), NULL),
(900105, N'fixture-aria-former', N'fixture-aria-former-pass', 1,
 CONVERT(DATETIME, '20000101', 112), CONVERT(DATETIME, '20500101', 112),
 CONVERT(DATETIME, '20200101', 112));
GO
""".format(db=database, columns=",\n".join(columns))


def main(argv):
    if len(argv) != 3:
        raise SystemExit("Pass read-only original Personnel.dll, CI-owned DB name, runner-temp output path")
    data = pathlib.Path(argv[0]).read_bytes()
    if hashlib.sha256(data).hexdigest() != PIN:
        raise ValueError("refuse unpinned original Personnel.dll")
    sql = make_sql(data, argv[1])
    pathlib.Path(argv[2]).write_text(sql, encoding="utf-8")
    print("Fixture SQL generated from pinned original EDMX for CI-owned user table only; NO database touched")


if __name__ == "__main__":
    main(sys.argv[1:])
