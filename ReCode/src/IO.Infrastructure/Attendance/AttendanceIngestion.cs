using System.Security.Cryptography;
using System.Text;
using IO.Domain.Attendance;
using IO.Infrastructure.Security;
using IO.Infrastructure.Storage;
using Microsoft.EntityFrameworkCore;

namespace IO.Infrastructure.Attendance;

/// <summary>Experimental, authorized synthetic ingestion; not a device protocol.</summary>
public sealed class AttendanceIngestion(IoDbContext db, PermissionTransaction transaction)
{
    public const string Manage = "attendance.ingest";
    public sealed record Receipt(Guid EventId, RawEventAppendResult Outcome, Guid? ConflictId = null);

    public Task<Guid> CreateSourceAsync(Guid actor, Guid? siteId, string name, CancellationToken ct = default) =>
        transaction.ExecuteAsync(actor, Manage, "attendance.source.created", async token =>
        {
            if (string.IsNullOrWhiteSpace(name) || name.Length > 200 || name.Any(char.IsControl))
                throw new ArgumentException("Invalid source name.");
            if (siteId is not null && !await db.Sites.AnyAsync(x => x.Id == siteId, token))
                throw new ArgumentException("Unknown site.");
            var id = Guid.NewGuid();
            db.EventSources.Add(new() { Id = id, SiteId = siteId, Name = name });
            return (id, id);
        }, ct);

    // Receipt time and event ID are generated by the server. Unidentified events
    // are stored separately, never guessed to be duplicates. Conflicts are
    // retained separately without altering the original immutable event.
    public Task<Receipt> AppendAsync(Guid actor, Guid sourceId, string? externalId, string? personId,
        DateTimeOffset? occurredAt, string? sourceZone, string? eventType, byte[] payload, CancellationToken ct = default) =>
        transaction.ExecuteAsync(actor, Manage, "attendance.received", async token =>
        {
            if (sourceId == Guid.Empty || payload is null || payload.Length > 1024 * 1024 ||
                (externalId is not null && (string.IsNullOrWhiteSpace(externalId) || externalId.Length > 180)) ||
                personId?.Length > 100 || sourceZone?.Length > 100 || eventType?.Length > 80)
                throw new ArgumentException("Invalid event envelope.");
            if (!await db.EventSources.AnyAsync(x => x.Id == sourceId, token)) throw new ArgumentException("Unknown source.");
            if (externalId is not null)
            {
                // The length of UTF-16 code units matters, including trailing NULs.
                var identity = Encoding.Unicode.GetBytes(externalId);
                var lockKey = Convert.ToHexString(SHA256.HashData(identity));
                await transaction.LockAsync("IO.Raw." + sourceId.ToString("N") + "." + lockKey, token);
                var existing = await db.RawAttendanceEvents.AsNoTracking().SingleOrDefaultAsync(x => x.SourceId == sourceId &&
                    EF.Property<byte[]>(x, "ExternalEventIdBytes") == identity &&
                    EF.Property<int?>(x, "ExternalEventIdByteLength") == identity.Length, token);
                if (existing is not null)
                {
                    var same = string.Equals(existing.ExternalEventId, externalId, StringComparison.Ordinal) &&
                        string.Equals(existing.SourceEmployeeIdentifier, personId, StringComparison.Ordinal) &&
                        existing.OccurredAtUtc == occurredAt?.ToUniversalTime() &&
                        string.Equals(existing.SourceTimeZoneId, sourceZone, StringComparison.Ordinal) &&
                        string.Equals(existing.ReportedEventType, eventType, StringComparison.Ordinal) &&
                        existing.SourcePayload.AsSpan().SequenceEqual(payload);
                    if (same) return (new Receipt(existing.Id, RawEventAppendResult.AlreadyRecorded), existing.Id);
                    var conflictId = Guid.NewGuid();
                    db.RawEventConflicts.Add(new() { Id = conflictId, OriginalEventId = existing.Id, SourceId = sourceId,
                        ExternalEventId = externalId, SourceEmployeeIdentifier = personId, OccurredAtUtc = occurredAt?.ToUniversalTime(),
                        ReceivedAtUtc = DateTimeOffset.UtcNow, SourceTimeZoneId = sourceZone, ReportedEventType = eventType, SourcePayload = payload.ToArray() });
                    return (new Receipt(existing.Id, RawEventAppendResult.ConflictingExternalIdentity, conflictId), conflictId);
                }
            }
            var id = Guid.NewGuid();
            db.RawAttendanceEvents.Add(new() { Id = id, SourceId = sourceId, ExternalEventId = externalId,
                SourceEmployeeIdentifier = personId, OccurredAtUtc = occurredAt?.ToUniversalTime(), ReceivedAtUtc = DateTimeOffset.UtcNow,
                SourceTimeZoneId = sourceZone, ReportedEventType = eventType, SourcePayload = payload.ToArray() });
            var added = new Receipt(id, externalId is null ? RawEventAppendResult.IdentityRequiresReview : RawEventAppendResult.Appended);
            return (added, id);
        }, ct);

    public Task<Guid> AddMappingAsync(Guid actor, Guid sourceId, string sourcePersonId, Guid employeeId,
        DateTimeOffset fromUtc, DateTimeOffset? untilUtcExclusive, CancellationToken ct = default) =>
        transaction.ExecuteAsync(actor, Manage, "attendance.mapping.created", async token =>
        {
            if (sourceId == Guid.Empty || employeeId == Guid.Empty || string.IsNullOrWhiteSpace(sourcePersonId) ||
                sourcePersonId.Length > 100 || sourcePersonId.Any(char.IsControl) || fromUtc.Offset != TimeSpan.Zero ||
                (untilUtcExclusive is not null && (untilUtcExclusive.Value.Offset != TimeSpan.Zero || untilUtcExclusive <= fromUtc)))
                throw new ArgumentException("Invalid source mapping.");
            var identity = Encoding.Unicode.GetBytes(sourcePersonId);
            await transaction.LockAsync("IO.SourcePerson." + sourceId.ToString("N") + "." + Convert.ToHexString(SHA256.HashData(identity)), token);
            var company = await (from source in db.EventSources
                                 join site in db.Sites on source.SiteId equals (Guid?)site.Id
                                 where source.Id == sourceId
                                 select (Guid?)site.CompanyId).SingleOrDefaultAsync(token);
            if (company is null || !await db.Employees.AnyAsync(x => x.Id == employeeId && x.CompanyId == company, token))
                throw new ArgumentException("Source must have a site in the employee's company.");
            if (await db.SourceEmployeeMappings.AnyAsync(x => x.SourceId == sourceId &&
                EF.Property<byte[]>(x, "SourcePersonIdBytes") == identity &&
                EF.Property<int>(x, "SourcePersonIdByteLength") == identity.Length &&
                (untilUtcExclusive == null || x.ValidFromUtc < untilUtcExclusive) &&
                (x.ValidUntilUtcExclusive == null || fromUtc < x.ValidUntilUtcExclusive), token))
                throw new DomainConflictException("Overlapping source identity mapping.");
            var id = Guid.NewGuid();
            db.SourceEmployeeMappings.Add(new() { Id = id, SourceId = sourceId, SourcePersonId = sourcePersonId, EmployeeId = employeeId,
                CompanyId = company.Value, ValidFromUtc = fromUtc, ValidUntilUtcExclusive = untilUtcExclusive });
            return (id, id);
        }, ct);

    public Task<object> ListMappingsAsync(Guid actor, Guid sourceId, int offset, CancellationToken ct = default) =>
        transaction.ExecuteAsync<object>(actor, Manage, "attendance.mappings.viewed", async token =>
        {
            if (sourceId == Guid.Empty || offset is < 0 or > 100000) throw new ArgumentException("Invalid page.");
            var items = await db.SourceEmployeeMappings.AsNoTracking().Where(x => x.SourceId == sourceId)
                .OrderBy(x => x.ValidFromUtc).ThenBy(x => x.Id).Skip(offset).Take(50)
                .Select(x => new { x.Id, x.SourceId, x.SourcePersonId, x.EmployeeId, x.CompanyId, x.ValidFromUtc, x.ValidUntilUtcExclusive })
                .ToListAsync(token);
            return (new { sourceId, offset, pageSize = 50, items }, sourceId);
        }, ct);

    // Unknown, malformed or ambiguous identities never resolve by guessing.
    public Task<object> ListResolutionAsync(Guid actor, Guid sourceId, int offset, CancellationToken ct = default) =>
        transaction.ExecuteAsync<object>(actor, Manage, "attendance.resolution.viewed", async token =>
        {
            if (sourceId == Guid.Empty || offset < 0 || offset > 100000) throw new ArgumentException("Invalid page.");
            var rows = await db.RawAttendanceEvents.AsNoTracking().Where(x => x.SourceId == sourceId)
                .OrderBy(x => x.ReceivedAtUtc).ThenBy(x => x.Id).Skip(offset).Take(50).ToListAsync(token);
            var items = new List<object>();
            foreach (var row in rows)
            {
                Guid? employee = null;
                if (row.SourceEmployeeIdentifier is not null && row.OccurredAtUtc is not null)
                {
                    var identity = Encoding.Unicode.GetBytes(row.SourceEmployeeIdentifier);
                    var candidates = await db.SourceEmployeeMappings.AsNoTracking().Where(x => x.SourceId == sourceId &&
                        EF.Property<byte[]>(x, "SourcePersonIdBytes") == identity && EF.Property<int>(x, "SourcePersonIdByteLength") == identity.Length &&
                        x.ValidFromUtc <= row.OccurredAtUtc && (x.ValidUntilUtcExclusive == null || row.OccurredAtUtc < x.ValidUntilUtcExclusive))
                        .Select(x => x.EmployeeId).Take(2).ToListAsync(token);
                    if (candidates.Count == 1) employee = candidates[0];
                }
                items.Add(new { row.Id, row.SourceEmployeeIdentifier, row.OccurredAtUtc, row.ReportedEventType, EmployeeId = employee,
                    Status = employee is null ? "requires-review" : "mapped" });
            }
            return (new { sourceId, offset, pageSize = 50, items }, sourceId);
        }, ct);

    public Task<object> ListConflictsAsync(Guid actor, Guid sourceId, int offset, CancellationToken ct = default) =>
        transaction.ExecuteAsync<object>(actor, Manage, "attendance.conflicts.viewed", async token =>
        {
            if (sourceId == Guid.Empty || offset < 0 || offset > 100000) throw new ArgumentException("Invalid page.");
            var items = await db.RawEventConflicts.AsNoTracking().Where(x => x.SourceId == sourceId)
                .OrderBy(x => x.ReceivedAtUtc).ThenBy(x => x.Id).Skip(offset).Take(50)
                .Select(x => new { x.Id, x.OriginalEventId, x.SourceId, x.ExternalEventId, x.SourceEmployeeIdentifier,
                    x.OccurredAtUtc, x.ReceivedAtUtc, x.SourceTimeZoneId, x.ReportedEventType }).ToListAsync(token);
            return (new { sourceId, offset, pageSize = 50, items }, sourceId);
        }, ct);

    public Task<object> GetConflictAsync(Guid actor, Guid conflictId, CancellationToken ct = default) =>
        transaction.ExecuteAsync<object>(actor, Manage, "attendance.conflict.viewed", async token =>
        {
            if (conflictId == Guid.Empty) throw new ArgumentException("Invalid conflict.");
            var item = await db.RawEventConflicts.AsNoTracking().Where(x => x.Id == conflictId)
                .Select(x => new { x.Id, x.OriginalEventId, x.SourceId, x.ExternalEventId, x.SourceEmployeeIdentifier,
                    x.OccurredAtUtc, x.ReceivedAtUtc, x.SourceTimeZoneId, x.ReportedEventType, x.SourcePayload })
                .SingleOrDefaultAsync(token) ?? throw new ArgumentException("Unknown conflict.");
            return (item, conflictId);
        }, ct);

    // Only globally authorized ingestion operators can inspect unassigned raw
    // records: source identity is not yet a trusted employee mapping.
    public Task<object> ListAsync(Guid actor, Guid sourceId, int offset, CancellationToken ct = default) =>
        transaction.ExecuteAsync<object>(actor, Manage, "attendance.raw.viewed", async token =>
        {
            if (sourceId == Guid.Empty || offset < 0 || offset > 100000) throw new ArgumentException("Invalid page.");
            var rows = await db.RawAttendanceEvents.AsNoTracking().Where(x => x.SourceId == sourceId)
                .OrderBy(x => x.ReceivedAtUtc).ThenBy(x => x.Id).Skip(offset).Take(50)
                .Select(x => new { x.Id, x.SourceId, x.ExternalEventId, x.SourceEmployeeIdentifier, x.OccurredAtUtc,
                    x.ReceivedAtUtc, x.SourceTimeZoneId, x.ReportedEventType }).ToListAsync(token);
            return (new { sourceId, offset, pageSize = 50, items = rows }, sourceId);
        }, ct);
}
