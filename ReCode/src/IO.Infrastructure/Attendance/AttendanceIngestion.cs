using System.Security.Cryptography;
using System.Text;
using IO.Domain.Attendance;
using IO.Infrastructure.Security;
using IO.Infrastructure.Storage;
using Microsoft.EntityFrameworkCore;

namespace IO.Infrastructure.Attendance;

/// <summary>Experimental, authorized synthetic ingestion; not a device protocol.</summary>
public sealed class AttendanceIngestion(IoDbContext db, PermissionTransaction transaction)
{
    public const string Manage = "attendance.ingest";
    public sealed record Receipt(Guid EventId, RawEventAppendResult Outcome);

    public Task<Guid> CreateSourceAsync(Guid actor, Guid? siteId, string name, CancellationToken ct = default) =>
        transaction.ExecuteAsync(actor, Manage, "attendance.source.created", async token =>
        {
            if (string.IsNullOrWhiteSpace(name) || name.Length > 200 || name.Any(char.IsControl))
                throw new ArgumentException("Invalid source name.");
            if (siteId is not null && !await db.Sites.AnyAsync(x => x.Id == siteId, token))
                throw new ArgumentException("Unknown site.");
            var id = Guid.NewGuid();
            db.EventSources.Add(new() { Id = id, SiteId = siteId, Name = name });
            return (id, id);
        }, ct);

    // Receipt time and event ID are generated by the server. Unidentified events
    // are stored separately, never guessed to be duplicates. A conflict returns
    // no success and the caller must retain its payload for review/retry.
    public Task<Receipt> AppendAsync(Guid actor, Guid sourceId, string? externalId, string? personId,
        DateTimeOffset? occurredAt, string? sourceZone, string? eventType, byte[] payload, CancellationToken ct = default) =>
        transaction.ExecuteAsync(actor, Manage, "attendance.received", async token =>
        {
            if (sourceId == Guid.Empty || payload is null || payload.Length > 1024 * 1024 ||
                (externalId is not null && (string.IsNullOrWhiteSpace(externalId) || externalId.Length > 180)) ||
                personId?.Length > 100 || sourceZone?.Length > 100 || eventType?.Length > 80)
                throw new ArgumentException("Invalid event envelope.");
            if (!await db.EventSources.AnyAsync(x => x.Id == sourceId, token)) throw new ArgumentException("Unknown source.");
            if (externalId is not null)
            {
                // The length of UTF-16 code units matters, including trailing NULs.
                var identity = Encoding.Unicode.GetBytes(externalId);
                var lockKey = Convert.ToHexString(SHA256.HashData(identity));
                await transaction.LockAsync("IO.Raw." + sourceId.ToString("N") + "." + lockKey, token);
                var existing = await db.RawAttendanceEvents.AsNoTracking().SingleOrDefaultAsync(x => x.SourceId == sourceId &&
                    EF.Property<byte[]>(x, "ExternalEventIdBytes") == identity &&
                    EF.Property<int?>(x, "ExternalEventIdByteLength") == identity.Length, token);
                if (existing is not null)
                {
                    var same = string.Equals(existing.ExternalEventId, externalId, StringComparison.Ordinal) &&
                        string.Equals(existing.SourceEmployeeIdentifier, personId, StringComparison.Ordinal) &&
                        existing.OccurredAtUtc == occurredAt?.ToUniversalTime() &&
                        string.Equals(existing.SourceTimeZoneId, sourceZone, StringComparison.Ordinal) &&
                        string.Equals(existing.ReportedEventType, eventType, StringComparison.Ordinal) &&
                        existing.SourcePayload.AsSpan().SequenceEqual(payload);
                    var receipt = new Receipt(existing.Id, same ? RawEventAppendResult.AlreadyRecorded : RawEventAppendResult.ConflictingExternalIdentity);
                    return (receipt, existing.Id);
                }
            }
            var id = Guid.NewGuid();
            db.RawAttendanceEvents.Add(new() { Id = id, SourceId = sourceId, ExternalEventId = externalId,
                SourceEmployeeIdentifier = personId, OccurredAtUtc = occurredAt?.ToUniversalTime(), ReceivedAtUtc = DateTimeOffset.UtcNow,
                SourceTimeZoneId = sourceZone, ReportedEventType = eventType, SourcePayload = payload.ToArray() });
            var added = new Receipt(id, externalId is null ? RawEventAppendResult.IdentityRequiresReview : RawEventAppendResult.Appended);
            return (added, id);
        }, ct);

    // Only globally authorized ingestion operators can inspect unassigned raw
    // records: source identity is not yet a trusted employee mapping.
    public Task<object> ListAsync(Guid actor, Guid sourceId, int offset, CancellationToken ct = default) =>
        transaction.ExecuteAsync<object>(actor, Manage, "attendance.raw.viewed", async token =>
        {
            if (sourceId == Guid.Empty || offset < 0 || offset > 100000) throw new ArgumentException("Invalid page.");
            var rows = await db.RawAttendanceEvents.AsNoTracking().Where(x => x.SourceId == sourceId)
                .OrderBy(x => x.ReceivedAtUtc).ThenBy(x => x.Id).Skip(offset).Take(50)
                .Select(x => new { x.Id, x.SourceId, x.ExternalEventId, x.SourceEmployeeIdentifier, x.OccurredAtUtc,
                    x.ReceivedAtUtc, x.SourceTimeZoneId, x.ReportedEventType }).ToListAsync(token);
            return (new { sourceId, offset, pageSize = 50, items = rows }, sourceId);
        }, ct);
}
